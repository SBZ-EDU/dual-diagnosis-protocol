def local_eval(scenario: dict, answer: str) -> tuple:
    """امتیازدهی کلمه‌کلیدیِ محلی برای پاسخ آزاد همراه (۰ تا ۱۰).

    خروجی: (score, feedback) — feedback همان قالب ارزیاب AI را دارد تا
    سازوکار نمایش/آرشیو بدون تغییر کار کند.
    """
    rules = LOCAL_RULES.get(scenario["id"]) or {}
    a = (answer or "").strip()
    score = 2 if a else 0
    crit = [w for w in rules.get("crit", []) if w in a]
    good = [w for w in rules.get("good", []) if w in a]
    bad = [w for w in rules.get("bad", []) if w in a]
    score += min(len(crit), 2) * 3 + min(len(good), 2)
    if bad:
        score = min(score, 2)
    score = max(0, min(10, score))
    fb = ("⚙️ *ارزیاب محلی* (هاست هوش مصنوعی متصل نیست)\n\n"
          f"نمره: {score} از ۱۰\n\n"
          "نکته‌ی آموزشی این سناریو:\n" + scenario["teach"])
    return score, fb
