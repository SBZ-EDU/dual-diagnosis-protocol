    """تاریخچه‌ی گفتگو: ۵ پرسش اخیر برای پیشنهاد درسِ آکادمی."""
    hist = context.user_data.setdefault("recent_questions", [])
    if question and (not hist or hist[-1] != question):
        hist.append(question)
        del hist[:-5]


