async def answer_question(update: Update, context: ContextTypes.DEFAULT_TYPE, question: str):
    question = (question or "").strip()
    if not question:
        await update.effective_message.reply_text("لطفاً سؤال خود را بنویسید.")
        return
    if throttled(update.effective_user.id, context):
        await update.effective_message.reply_text(
            "🙏 پاسخ قبلی‌ام هنوز در حال آماده‌شدن است — لطفاً چند لحظه صبر کن؛ بعد دوباره بپرس.")
        return
    # --- حافظه‌ی شخصی: «اسم من X است» → ذخیره؛ پرسش از خود/تاریخچه → پاسخ محلی ---
    m = _NAME_SET_RE.search(question.strip())
    if m and (m.group(1) or "").strip():
        given = m.group(1).strip()
        context.user_data["profile_name"] = given
        await update.effective_message.reply_text(
            f"خوشحالم که رفاقت شدم، {given} 🤍 اسمت را به خاطر می‌سپارم.",
            reply_markup=_kb_for(context))
        return
    if _SELF_Q_RE.search(question):
        await send_long(update, _profile_text(update, context),
                        reply_markup=_kb_for(context))
        return
    typing = asyncio.create_task(_keep_typing(update.effective_chat.id, context))
    try:
        # در نخ جدا: embedding روی Ollama و جست‌وجوی IDF نباید حلقه‌ی رویداد را قفل کنند
        _remember_question(context, question)  # تاریخچه‌ی گفتگو برای پیشنهاد درس
        ai_q, srcs = await asyncio.to_thread(
            build_grounded_question, question, _profile_context(context))
        data = await asyncio.to_thread(ask_ai, ai_q, get_role(context))  # بخش هوش مصنوعی
        if data:
            answer = _sanitize_ai_text(_shorten_answer(data["answer"].rstrip()))
            lines = [answer, ""]
            if get_role(context) == "patient":
                # بیمار: بدون متای فنی — فقط پاسخ + یادآوری کوتاه
                lines.append(DISCLAIMER)
            else:
                src = data.get("source") or ""
                if src:
                    lines.append(f"🧠 مدل پاسخ‌دهنده: {src}")
                if srcs:
                    lines.append("📚 منابع دانش: " + "، ".join(s[:44] for s in srcs))
                lines.append(DISCLAIMER)
            await send_long(update, "\n".join(lines), reply_markup=_kb_for(context))
            return
    except Exception as e:
        log.warning("دستیار هوش مصنوعی در دسترس نیست (%s)؛ پاسخ از پروتکل محلی.", e)
    # حالت آفلاین/بدون AI: پایگاه دانش محلی → متن پروتکل
    ctx = await asyncio.to_thread(search_corpus, question, 1)
    if ctx:
        parts = [f"📚 *از پایگاه دانش محلی*\n({c.get('source', '—')})\n\n{(c.get('text') or '')[:600]}"
                 for c in ctx]
        await send_long(update, "\n\n———\n\n".join(parts) + "\n\n" + DISCLAIMER,
                        reply_markup=_kb_for(context))
    else:
        hit = await asyncio.to_thread(search_protocol, question)
        if hit:
            await send_long(update, f"📖 *از پروتکل درمان — {hit['title']}*\n\n{hit['text']}\n\n{DISCLAIMER}",
                            parse_mode="Markdown")
        else:
            await update.effective_message.reply_text(
                "در حال حاضر پاسخی پیدا نشد. لطفاً سؤال را دقیق‌تر بپرسید یا بعداً تلاش کنید.\n" + DISCLAIMER)


