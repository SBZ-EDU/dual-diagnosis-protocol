def _channel_promo() -> str:
    """لینک کانال برای دعوت دیگران (در پیام‌ها و پست‌های کانال)."""
    if not TELEGRAM_CHANNEL_ID:
        return ""
    return f"\n\n🔔 این آموزش را به خانواده‌های دیگری که در این مسیرند بفرستید: {channel_link()}"


def _post_with_meta(entry):
    """ورودی سری‌ها را به (title, body, source, tags, question) تبدیل می‌کند."""
    title, body, source = entry[0], entry[1], entry[2]
    tags = list(entry[3]) if len(entry) >= 4 and entry[3] else []
    question = entry[4] if len(entry) >= 5 else ""
    return title, body, source, tags, question


def _render_channel_post(label: str, entry) -> str:
    """قالب یکسان پست کانال: عنوان + متن + پرسش تعاملی + منبع + هشتگ‌ها (HTML)."""
    title, body, source, tags, question = _post_with_meta(entry)
    text = f"{label} | <b>{title}</b>\n\n{body}"
    if question:
        text += f"\n\n💬 {question}"
    text += f"\n\n📖 منبع: {source}"
    if tags:
        text += "\n🏷 " + " ".join("#" + t for t in tags)
    text += f"{_channel_promo()}\n{DISCLAIMER}"
    return text


