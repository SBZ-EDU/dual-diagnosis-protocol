def _profile_text(update: Update, context: ContextTypes.DEFAULT_TYPE) -> str:
    """کارت «من و مسیرم» — فقط از داده‌های محلی خودِ کاربر."""
    name = _user_display_name(update, context)
    role = get_role(context)
