def _norm_fa(s: str) -> str:
    """نرمال‌سازی فارسی برای جست‌وجوی کلیدواژه‌ای."""
    return s.replace("ي", "ی").replace("ك", "ک").replace(chr(0x200C), " ").lower()


# وکتورهای معنایی از پیش محاسبه‌شده (bge-m3 محلی)
_VECS = None
try:
    import numpy as _np
    _z = _np.load(os.path.join(BOT_DIR, "..", "data", "vectors_semantic.npz"))
    _v = _z["vectors"].astype("float32")
    if len(_v) == len(CORPUS):
        _VECS = _v
except Exception:
    _VECS = None


def _embed_query(query: str):
    """embedding پرسش با bge-m3 روی Ollama محلی (در صورت در دسترس بودن)."""
    try:
        body = json.dumps({"model": "bge-m3", "input": [query[:1000]]}).encode()
        req = urllib.request.Request("http://127.0.0.1:11434/api/embed",
                                     data=body, method="POST",
                                     headers={"content-type": "application/json"})
        with urllib.request.urlopen(req, timeout=10) as r:
            e = json.loads(r.read().decode())["embeddings"][0]
        v = _np.array(e, dtype="float32")
        n = float(_np.linalg.norm(v))
        return v / n if n > 0 else None
    except Exception:
        return None


def search_corpus(query: str, k: int = 3) -> list:
    """جست‌وجوی معنایی محلی (bge-m3) با fallback جست‌وجوی IDF کلیدواژه‌ای."""
    if _VECS is not None:
        v = _embed_query(query)
        if v is not None:
            sims = _VECS @ v
            idx = _np.argsort(-sims)[:k]
            if float(sims[int(idx[0])]) > 0.35:
                return [CORPUS[int(i)] for i in idx]
    return _search_corpus_idf(query, k)


_IDF_NORMED: list | None = None


def _idf_normed() -> list:
    """نرمال‌شده‌ی پایگاه دانش — فقط یک بار محاسبه و در کش ماژول."""
    global _IDF_NORMED
    if _IDF_NORMED is None:
        _IDF_NORMED = [_norm_fa(c.get("text") or "") for c in CORPUS]
    return _IDF_NORMED


def _search_corpus_idf(query: str, k: int = 3) -> list:
    """جست‌وجوی IDF-وزن‌دار در پایگاه دانش محلی (فارسی + انگلیسی)."""
    if not CORPUS:
        return []
    normed = _idf_normed()
    toks = {w for w in _norm_fa(query).split() if len(w) > 2 and w not in _FA_STOP}
    if not toks:
        return []
    weights = {}
    for t in toks:
        df = sum(1 for n in normed if t in n)
        if df:
            weights[t] = 1.0 / (df ** 0.5)
    if not weights:
        return []
    scored = []
    for i, n in enumerate(normed):
        sc = sum(w for t, w in weights.items() if t in n)
        if sc > 0:
            scored.append((sc, i))
    scored.sort(reverse=True)
    if not scored or scored[0][0] < 0.15:
        return []
    return [CORPUS[i] for _, i in scored[:k]]


def build_grounded_question(question: str, user_context: str = "") -> tuple:
    """پرسش کاربر + شواهدِ پایگاه دانش + بافتِ شخصی → پرامپت مستند (KAG)."""
    ctx = search_corpus(question)
    if not ctx:
        return question, []
    evid = "\n".join(
        f"شواهد {i + 1}. ({c.get('source', '—')}): {(c.get('text') or '')[:700]}"
        for i, c in enumerate(ctx))
    srcs = sorted({(c.get("source") or "—") for c in ctx})
    uctx = (f"\n\nبافتِ کاربر (پاسخ را متناسب با آن تنظیم کن — سن، نسبت، کار و وضعیت مالی):\n{user_context}\n"
            if user_context else "")
    prompt = (f"شواهد:\n{evid}\n{uctx}\nپرسش: {question}\n\n"
              "فقط بر اساس شواهد بالا پاسخ بده و به شماره‌ی شواهد ارجاع بده؛ "
              "اگر شواهد کافی نیست صریح بگو.")
    return prompt, srcs


