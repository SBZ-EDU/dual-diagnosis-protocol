        recent = sorted(dlog.items(), key=lambda kv: kv[0], reverse=True)[:5]
        if recent:
            lines.append("آخرین روزها:")
            for dk, e in recent:
                m = MOOD_LABELS[e["m"]].split(" ", 1)[1] if "m" in e else "—"
