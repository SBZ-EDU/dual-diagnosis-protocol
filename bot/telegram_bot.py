    prog = context.user_data.get("academy") or {}
    modules = _active_modules(context)
    done_mod = sum(1 for m in modules if m["id"] in prog)
    tot_mod = len(modules)
    hist = context.user_data.get("risk_history") or []
    pts = context.user_data.get("level_pts") or 0
