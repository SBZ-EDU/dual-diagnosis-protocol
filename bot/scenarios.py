def build_eval_prompt(scenario: dict, answer: str) -> str:
    """پرامپت ارزیابی پاسخ همراه توسط هوش مصنوعی سایت."""
    return (
        "تو ارزیاب بالینی آموزشِ «همراه» بیمار با تشخیص دوگانه (سایکوز + مصرف مواد) هستی.\n"
        f"سناریو: «{scenario['title']}»\n"
        f"شرایط: {scenario['text']}\n"
        f"پاسخِ همراه: «{answer}»\n\n"
        "پاسخ این همراه را از نظر بالینی ارزیابی کن. فقط و فقط با این قالب و حداکثر ۶ خط جواب بده:\n"
        "نمره: X از ۱۰\n"
        "نقاط قوت: …\n"
        "اصلاح کلیدی: …\n"
        "نیاز به تماس فوری با متخصص: بله/خیر + یک دلیل"
    )


